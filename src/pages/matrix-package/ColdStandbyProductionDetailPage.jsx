function normalizeH5PackageName(packageName) {
  return String(packageName || '')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, '')
    .replace(/-+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function normalizeH5Domain(domainInfo) {
  return String(domainInfo || '')
    .trim()
    .split(/[\s,，;；]+/)[0]
    .replace(/^[a-z][a-z\d+.-]*:\/\//i, '')
    .split(/[/?#]/)[0]
    .replace(/^\.+|\.+$/g, '')
    .toLowerCase()
}

